"""Rule catalog: one Markdown page per business rule, generated from the dbt YAML.

    docs/rules/README.md                 every domain, every rule
    docs/rules/<domain>/README.md        the domain's rules by layer (bronze listed inline)
    docs/rules/<domain>/<rule>.md        one page per silver/gold rule

The dbt YAML is the source of truth (rule, arguments, severity, description) and the
generators say which scenario trips each rule. Pages must not be edited by hand: change the
YAML and run `python -m pipeline docs`; `--check` fails when the pages are out of date.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from pipeline.config import DBT_PROJECT_DIR, LAYERS, PROJECT_ROOT, load_domains

DOCS_DIR = PROJECT_ROOT / "docs" / "rules"
HEADER = "<!-- GENERATED by `python -m pipeline docs` from dbt/models/**/_*.yml — do not edit. -->\n"
BUSINESS_LAYERS = ("silver", "gold")


@dataclass
class Rule:
    name: str
    domain: str
    layer: str
    model: str
    column: str | None
    check: str
    arguments: dict
    severity: str
    description: str
    source: Path  # relative to the project root
    scenarios: list = field(default_factory=list)

    @property
    def schema(self) -> str:
        return f"{self.domain}_gold_staging" if self.layer == "gold" else f"{self.domain}_{self.layer}"


def _ref_name(value) -> str:
    match = re.search(r"ref\(['\"]([^'\"]+)['\"]\)", str(value))
    return match.group(1) if match else str(value)


def describe_check(rule: Rule) -> str:
    """What the rule verifies, in one sentence."""
    a, col = rule.arguments, f"`{rule.column}`" if rule.column else None
    if rule.check == "unique":
        return f"{col} is unique: no two rows share the same value."
    if rule.check == "not_null":
        return f"{col} is never null."
    if rule.check == "accepted_values":
        return f"{col} is one of: " + ", ".join(f"`{v}`" for v in a["values"]) + "."
    if rule.check == "relationships":
        return f"Every {col} exists as `{a['field']}` in `{_ref_name(a['to'])}`."
    if rule.check == "value_between":
        lo, hi = a.get("min_value"), a.get("max_value")
        if lo is not None and hi is not None:
            return f"{col} is between {lo} and {hi} (inclusive)."
        return f"{col} is at least {lo}." if lo is not None else f"{col} is at most {hi}."
    if rule.check == "matches_pattern":
        return f"{col} matches the regular expression `{a['pattern']}`."
    if rule.check == "not_in_future":
        return f"{col} is not later than now (+{a.get('tolerance_minutes', 5)} minutes of tolerance)."
    if rule.check == "expression_is_true":
        return f"Every row satisfies `{' '.join(str(a['expression']).split())}`."
    if rule.check == "unique_combination":
        return "The combination of " + ", ".join(f"`{c}`" for c in a["columns"]) + " is unique."
    if rule.check == "row_count_between":
        hi = a.get("max_value")
        return f"The model has at least {a.get('min_value', 1)} row(s)" + (f" and at most {hi}." if hi else ".")
    if rule.check == "reconciles_with":
        left = f"`{a['expression']}`" + (f" where `{a['filter']}`" if a.get("filter") else "")
        right = f"`{a.get('compare_expression') or a['expression']}` of `{_ref_name(a['compare_model'])}`"
        if a.get("compare_filter"):
            right += f" where `{a['compare_filter']}`"
        return f"{left} equals {right}, within {a.get('tolerance', 0.01)}."
    if rule.check == "castable":
        return f"Every non-null {col} can be cast to `{a['to']}`."
    return f"Generic test `{rule.check}` with arguments {a}."


def collect_rules(dbt_dir: Path | None = None) -> list[Rule]:
    dbt_dir = dbt_dir or DBT_PROJECT_DIR
    from pipeline.generators import GENERATORS  # imported lazily: generators import config too

    scenarios = {}
    for domain, gen in GENERATORS.items():
        for s in gen.scenarios().values():
            scenarios.setdefault(s.expected_rule, []).append((domain, s))

    rules = []
    for path in sorted((dbt_dir / "models").glob("*/*/_*.yml")):
        domain, layer = path.parent.parent.name, path.parent.name
        if layer not in LAYERS:
            continue
        for model in (yaml.safe_load(path.read_text()) or {}).get("models", []):
            entries = [(None, t) for t in model.get("data_tests") or []]
            entries += [(c["name"], t) for c in model.get("columns") or [] for t in c.get("data_tests") or []]
            for column, test in entries:
                if not isinstance(test, dict):
                    continue
                ((check, spec),) = test.items()
                spec = spec or {}
                rules.append(Rule(
                    name=spec.get("name") or f"{check}_{model['name']}_{column}",
                    domain=domain, layer=layer, model=model["name"], column=column, check=check,
                    arguments=spec.get("arguments") or {},
                    severity=(spec.get("config") or {}).get("severity", "error"),
                    description=" ".join(str(spec.get("description", "")).split()),
                    source=path.relative_to(PROJECT_ROOT) if path.is_relative_to(PROJECT_ROOT) else path,
                    scenarios=[s for d, s in scenarios.get(spec.get("name"), []) if d == domain],
                ))
    return rules


def _rule_page(rule: Rule) -> str:
    stops = rule.severity == "error"
    lines = [
        HEADER,
        f"# `{rule.name}`",
        "",
        f"> {rule.description or '_No description yet: add one to the rule in its YAML._'}",
        "",
        "| | |",
        "|---|---|",
        f"| Domain | [{rule.domain}](README.md) |",
        f"| Layer | **{rule.layer}** — evaluated by the `{rule.layer}` gate |",
        f"| Model | `{rule.model}` (`{rule.schema}.{rule.model}`) |",
    ]
    if rule.column:
        lines.append(f"| Column | `{rule.column}` |")
    lines += [
        f"| Check | `{rule.check}` |",
        f"| Severity | `{rule.severity}` — " + ("a violation **stops the pipeline**" if stops else "reported, does not stop the pipeline") + " |",
        f"| Defined in | [{rule.source}](../../../{rule.source}) |",
        "",
        "## What it checks",
        "",
        describe_check(rule),
        "",
        "## When it fails",
        "",
    ]
    if stops:
        downstream = {"silver": "gold and `publish_gold` don't run", "gold": "`publish_gold` doesn't run"}[rule.layer]
        lines.append(
            f"The `{rule.layer}` task of `medallion_{rule.domain}` fails, {downstream}, and the batch is never "
            f"added to `{rule.domain}_gold`: consumers keep the batches published before. `quality_report` "
            f"marks the run as blocked and sends the alert, if one is configured."
        )
    else:
        lines.append(
            "The violation is recorded in the quality report and `dq_audit`, and the batch is still published. "
            "Set `ALERT_ON_WARNINGS=true` to be notified."
        )
    lines += ["", f"The rows that broke the rule in its latest evaluation are kept in `dq_audit.{rule.name}`.", ""]

    lines += ["## Tested by", ""]
    if rule.scenarios:
        for s in rule.scenarios:
            lines += [
                f"Scenario **`{s.name}`**: {s.description}.",
                "",
                "```bash",
                f"make generate DOMAIN={rule.domain} SCENARIO={s.name} BATCH=2026-10-20_{s.name}",
                f"make pipeline DOMAIN={rule.domain} BATCH=2026-10-20_{s.name}",
                "```",
                "",
            ]
    else:
        lines += ["No sample-data scenario trips this rule yet: it guards against cases the generators don't produce.", ""]

    lines += [
        "## Investigate",
        "",
        "```sql",
        "-- rows that broke the rule last time it ran",
        f"select * from dq_audit.{rule.name};",
        "",
        "-- history of the rule",
        "select batch_id, status, failures, recorded_at",
        "from dq_audit.rule_results",
        f"where rule = '{rule.name}'",
        "order by recorded_at desc;",
        "```",
        "",
    ]
    if rule.arguments:
        lines += ["## Definition", "", "```yaml", yaml.safe_dump({rule.check: rule.arguments}, sort_keys=False).rstrip(), "```", ""]
    return "\n".join(lines)


_REF = re.compile(r"ref\(\s*['\"]([^'\"]+)['\"]\s*\)")
_SOURCE = re.compile(r"source\(\s*['\"]([^'\"]+)['\"]\s*,\s*['\"]([^'\"]+)['\"]\s*\)")


def lineage_mermaid(domain: str, rules: list[Rule], dbt_dir: Path | None = None) -> str:
    """Mermaid flowchart of the domain's models, read from the refs/sources in their SQL."""
    dbt_dir = dbt_dir or DBT_PROJECT_DIR
    per_model: dict[str, int] = {}
    for r in rules:
        per_model[r.model] = per_model.get(r.model, 0) + 1

    lines = ["flowchart LR"]
    edges, raw_tables = [], []
    layers = {}
    for layer in LAYERS:
        layers[layer] = sorted((dbt_dir / "models" / domain / layer).glob("*.sql"))
        for sql in layers[layer]:
            text = sql.read_text()
            for ref in _REF.findall(text):
                edges.append((ref, sql.stem))
            for _, table in _SOURCE.findall(text):
                raw_tables.append(table)
                edges.append((f"raw__{table}", sql.stem))

    lines.append(f'  subgraph raw["{domain}_raw"]')
    lines += [f'    raw__{t}[("{t}")]' for t in sorted(set(raw_tables))]
    lines.append("  end")
    titles = {"bronze": f"{domain}_bronze", "silver": f"{domain}_silver", "gold": f"{domain}_gold"}
    for layer in LAYERS:
        lines.append(f'  subgraph {layer}["{titles[layer]}"]')
        for sql in layers[layer]:
            n = per_model.get(sql.stem, 0)
            lines.append(f'    {sql.stem}["{sql.stem}<br/>{n} rule{"s" if n != 1 else ""}"]')
        lines.append("  end")
    lines += [f"  {a} --> {b}" for a, b in edges]
    # Cross-layer checks: gold must add up to the silver it was built from.
    for r in rules:
        if r.check == "reconciles_with":
            lines.append(f"  {r.model} -. reconciles .-> {_ref_name(r.arguments['compare_model'])}")
    lines += [
        "  classDef raw fill:#eceff1,stroke:#78909c,color:#1f2933",
        "  classDef bronze fill:#f3e0c7,stroke:#a1662f,color:#1f2933",
        "  classDef silver fill:#e8eaf0,stroke:#8790a3,color:#1f2933",
        "  classDef gold fill:#fff3c4,stroke:#c9a227,color:#1f2933",
        "  class " + ",".join(f"raw__{t}" for t in sorted(set(raw_tables))) + " raw",
    ]
    for layer in LAYERS:
        if layers[layer]:
            lines.append(f"  class {','.join(p.stem for p in layers[layer])} {layer}")
    return "\n".join(lines)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _domain_page(domain: str, description: str, rules: list[Rule]) -> str:
    business = [r for r in rules if r.layer in BUSINESS_LAYERS]
    lines = [
        HEADER,
        f"# {domain} rules",
        "",
        description,
        "",
        f"{len(rules)} rules: {sum(r.layer == 'bronze' for r in rules)} structural (bronze), "
        f"{len(business)} business (silver and gold). Back to the [catalog](../README.md).",
        "",
        "## Lineage",
        "",
        "Generated from the `ref()`/`source()` calls in the models; each box shows how many rules guard it. "
        "Raw tables hold every batch as text, bronze models are views of the current batch, silver is typed "
        "and cleaned, and gold is built in `_gold_staging` and published into `_gold`. Dotted arrows are "
        "cross-layer reconciliation rules.",
        "",
        "```mermaid",
        lineage_mermaid(domain, rules),
        "```",
        "",
    ]
    for layer in BUSINESS_LAYERS:
        layer_rules = [r for r in business if r.layer == layer]
        lines += [f"## {layer.capitalize()}", "", "| Rule | Model | Checks | Severity | Scenario |", "|---|---|---|---|---|"]
        for r in layer_rules:
            scenario = ", ".join(f"`{s.name}`" for s in r.scenarios) or "—"
            lines.append(
                f"| [`{r.name}`]({r.name}.md) | `{r.model}` | {_cell(r.description or describe_check(r))} "
                f"| {r.severity} | {scenario} |"
            )
        lines.append("")
    bronze = [r for r in rules if r.layer == "bronze"]
    lines += [
        "## Bronze (generated from the data contract)",
        "",
        f"Structural rules derived from `include/domains/{domain}.yml` by `make scaffold`: every entity is "
        "non-empty, required columns are present and typed columns are castable. They don't get their own page.",
        "",
        "| Rule | Model | Checks | Scenario |",
        "|---|---|---|---|",
    ]
    for r in bronze:
        scenario = ", ".join(f"`{s.name}`" for s in r.scenarios) or "—"
        lines.append(f"| `{r.name}` | `{r.model}` | {_cell(describe_check(r))} | {scenario} |")
    lines.append("")
    return "\n".join(lines)


def _catalog_page(rules: list[Rule], domains: dict) -> str:
    lines = [
        HEADER,
        "# Rule catalog",
        "",
        "Every data quality rule of the pipeline, generated from the dbt YAML. Rules with severity `error` "
        "stop the pipeline at their layer: the batch never reaches the domain's gold schema. Structural "
        "bronze rules come from the data contracts; silver and gold rules are the business rules and each "
        "has its own page.",
        "",
        "| Domain | Bronze | Silver | Gold | Total |",
        "|---|---|---|---|---|",
    ]
    for d in domains:
        dr = [r for r in rules if r.domain == d]
        counts = [sum(r.layer == layer for r in dr) for layer in LAYERS]
        lines.append(f"| [{d}]({d}/README.md) | {counts[0]} | {counts[1]} | {counts[2]} | {len(dr)} |")
    lines += [f"| **Total** | {sum(r.layer == 'bronze' for r in rules)} | {sum(r.layer == 'silver' for r in rules)} "
              f"| {sum(r.layer == 'gold' for r in rules)} | **{len(rules)}** |", ""]
    for d in domains:
        lines += [f"## {d}", "", "| Rule | Layer | What it guarantees |", "|---|---|---|"]
        for r in (r for r in rules if r.domain == d and r.layer in BUSINESS_LAYERS):
            lines.append(f"| [`{r.name}`]({d}/{r.name}.md) | {r.layer} | {_cell(r.description or describe_check(r))} |")
        lines.append("")
    lines += [
        "## Adding or changing a rule",
        "",
        "Edit the rule in `dbt/models/<domain>/<layer>/_<layer>.yml` (give it a `name` and a `description`), "
        "then regenerate these pages with `python -m pipeline docs`. CI fails if they are out of date.",
        "",
    ]
    return "\n".join(lines)


def render(dbt_dir: Path | None = None) -> dict[Path, str]:
    """Doc path (relative to docs/rules) -> content."""
    rules = collect_rules(dbt_dir)
    domains = {name: d.description for name, d in load_domains().items() if any(r.domain == name for r in rules)}
    files = {Path("README.md"): _catalog_page(rules, domains)}
    for domain, description in domains.items():
        domain_rules = [r for r in rules if r.domain == domain]
        files[Path(domain) / "README.md"] = _domain_page(domain, description, domain_rules)
        for r in domain_rules:
            if r.layer in BUSINESS_LAYERS:
                files[Path(domain) / f"{r.name}.md"] = _rule_page(r)
    return files


def stale_files(docs_dir: Path | None = None) -> list[Path]:
    docs_dir = docs_dir or DOCS_DIR
    rendered = render()
    stale = [p for p, c in rendered.items() if not (docs_dir / p).is_file() or (docs_dir / p).read_text() != c]
    stale += [p.relative_to(docs_dir) for p in docs_dir.rglob("*.md") if p.relative_to(docs_dir) not in rendered]
    return sorted(stale)


def write(docs_dir: Path | None = None) -> list[Path]:
    docs_dir = docs_dir or DOCS_DIR
    rendered = render()
    changed = stale_files(docs_dir)
    for path in changed:
        target = docs_dir / path
        if path in rendered:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(rendered[path])
        else:
            target.unlink()  # page of a rule that no longer exists
    return changed
